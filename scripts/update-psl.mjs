// Regenerates lib/psl-data.js from the Public Suffix List (https://publicsuffix.org, MPL-2.0).
// The extension never fetches the list itself: run this by hand now and then, review the diff
// and commit it.
//
//   node scripts/update-psl.mjs                  # download the current list
//   node scripts/update-psl.mjs path/to/list.dat # or convert a local copy
import { readFileSync, writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";

const SOURCE = "https://publicsuffix.org/list/public_suffix_list.dat";
const OUT = new URL("../lib/psl-data.js", import.meta.url);

const text = process.argv[2]
  ? readFileSync(process.argv[2], "utf8")
  : await (await fetch(SOURCE)).text();

// Rules are Unicode in the list; URL hands us hostnames in ASCII (punycode), so convert them.
// "*.ck" and "!www.ck" keep their prefix; only the domain part is converted.
const rules = [];
for (const raw of text.split("\n")) {
  const line = raw.trim().split(/\s/)[0];
  if (!line || line.startsWith("//")) continue;
  const prefix = line.startsWith("!") ? "!" : line.startsWith("*.") ? "*." : "";
  const ascii = domainToASCII(line.slice(prefix.length));
  if (!ascii) throw new Error(`Can't convert rule: ${line}`);
  rules.push(prefix + ascii);
}
if (rules.length < 5000) throw new Error(`Only ${rules.length} rules: download looks wrong`);

const version = text.match(/^\/\/ VERSION: (.+)$/m)?.[1] ?? "unknown";
writeFileSync(OUT, `// Generated by scripts/update-psl.mjs: do not edit by hand.
// Public Suffix List, ${SOURCE}
// Version: ${version}, ${rules.length} rules (ICANN and private domains), converted to ASCII.
//
// This Source Code Form is subject to the terms of the Mozilla Public License, v. 2.0. If a copy
// of the MPL was not distributed with this file, You can obtain one at https://mozilla.org/MPL/2.0/.
globalThis.PSL_RULES = ${JSON.stringify(rules.join("\n"))};
`);
console.log(`Wrote ${rules.length} rules (version ${version}) to lib/psl-data.js`);
